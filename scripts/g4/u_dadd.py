def s(x):
    """Decimal → 글자 (끝의 0 없앰)"""
    x = Dc(x).normalize()
    t = format(x, 'f')
    return t
def bad_align(a, b, op):
    """소수점을 맞추지 않고 끝자리를 맞추어 계산한 값 (예: 3.5 + 1.25 → 0.35 + 1.25 처럼)"""
    da, db = -Dc(a).as_tuple().exponent, -Dc(b).as_tuple().exponent
    if da == db: return None
    k = max(da, db)
    ia, ib = int(Dc(a) * 10 ** da), int(Dc(b) * 10 ** db)
    r = ia + ib if op == '+' else ia - ib
    return s(Dc(r) / Dc(10 ** k)) if r > 0 else None


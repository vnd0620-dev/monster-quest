def MV(*a): return '[[fig:mv:' + ':'.join(map(str, a)) + ']]'
def mvtxt(dx, dy):
    parts = []
    if dx: parts.append(f'{"오른쪽" if dx > 0 else "왼쪽"}으로 {abs(dx)}칸')
    if dy: parts.append(f'{"위쪽" if dy > 0 else "아래쪽"}으로 {abs(dy)}칸')
    return ', '.join(parts) + ' 이동'


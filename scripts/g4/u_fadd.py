def fs(n, d):
    """분자 n / 분모 d 를 약분 없이 쓰기 (가분수면 대분수로)"""
    w, r = divmod(n, d)
    if r == 0: return str(w)
    return f'{w} {r}/{d}' if w else f'{r}/{d}'
def tm(w, n, d):
    """대분수 글자 (w 자연수, n 분자) — 자연수만이면 w"""
    return f'{w} {n}/{d}' if w and n else (str(w) if not n else f'{n}/{d}')


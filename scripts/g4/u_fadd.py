        w = [(tm(w1 - w2, n2, den), 'swap'), (tm(w1 - w2, den - n2, den), 'borrow'), (tm(w1 - w2 - 1, n2, den) if w1 - w2 - 1 else f'{n2 + 1}/{den}', 'borrow'), (fs(A - C + 1, den), 'calc')]
        c = tm(w2, n2, den)
        tx = text or f'{w1} − {c}를 계산하세요.'
        ex = f'{w1} = {w1 - 1} {den}/{den}로 바꾸면 {w1 - 1} {den}/{den} − {c} = {ans}이에요.'
        return q(qid, d, tx, ans, w, f'{w1}에서 1을 {den}/{den}로 바꾸어요.', ex, f'첫 단계: {w1}을 {w1 - 1}과 {den}/{den}로 나누어요', {'expr': f'{w1} − {c}'})

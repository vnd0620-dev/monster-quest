        h2 = why or f'{expr} 을 차례로 계산해요.'
        explain = f'{expr} = {F(ans)} 이므로 답은 {ieyo(A)}.'
        return Q(b, qid, diff, t, A, cands_of(expr, ans, unit, extra, sv), hint or {'sd': H1, 'dd': H2, 'nf': H3, 'mul': H4}[key], h2, explain, STEP[key], {'expr': expr})


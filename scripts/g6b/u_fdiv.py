        if unit in COUNT:  # 개수·돈은 자연수 보기만
            out = list(extra)
            for m, tag in MODES:
                v = safe_ev(expr, m)
                if v is not None and v != ans and v.denominator == 1: out.append((F(v) + unit, tag))
            if step_val is not None and step_val.denominator == 1: out.append((F(step_val) + unit, 'step'))

def F(s): return Fr(s)
def toks(expr): return re.findall(r'\d+(?:\.\d+)?|[×+−]', expr)

def ev(expr, kind='ok', order=False):
    t = toks(expr)
    vals = [F(t[0])]; ops = []
    for i in range(1, len(t), 2):
        ops.append(t[i]); vals.append(F(t[i + 1]))
    first = [True]
    def mul(a, c):
        if first[0] and kind != 'ok':
            first[0] = False
            p = a * c
            if kind == 'x10': return p * 10
            if kind == 'd10': return p / 10
            if kind == 'add': return a + c
            if kind == 'nopoint':
                return F(dstr(a).replace('.', '')) * F(dstr(c).replace('.', ''))
        return a * c
    if not order:
        i = 0
        while i < len(ops):
            if ops[i] == '×':
                vals[i:i + 2] = [mul(vals[i], vals[i + 1])]; ops.pop(i)
            else:
                i += 1
    while ops:
        op = ops.pop(0)
        a, c = vals[0], vals[1]
        vals[0:2] = [a + c if op == '+' else a - c if op == '−' else mul(a, c)]
    return vals[0]


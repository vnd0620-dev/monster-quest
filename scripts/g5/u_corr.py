    # ── ③ □, △를 사용하여 식으로 나타내기 ──
    def formula_q(qid, diff, r):
        cands = [(f'△ = □ {op} {k}', tag) for (op, k), tag in r.wrong_rules()]
        cands.append((f'□ = △ {r.op} {r.k}', 'swap'))
        cands.append((f'△ = □ {r.op} {r.k + 1}', 'guess'))
        return Q(b, qid, diff, f'{r.spec()} □와 △ 사이의 대응 관계를 식으로 나타내면?', r.formula(), cands,
                 f'말로 먼저 나타내 봐요. 예: △는 □의 몇 배? 또는 □보다 몇 큰가?', f'{r.say()}. 이것을 식으로 쓰면 △ = □ ○ (수) 모양이에요.',
                 f'{r.say()}. 그래서 식은 {r.formula()} 예요.', f'첫 단계: □가 {r.top[0]}일 때 △가 {iga(str(r.f(r.top[0])))} 되는 계산을 찾아요')
    def use_q(qid, diff, op, k, a):
        r = Rel(op, k, 'tc', [1, 2, 3, 4]); ans = r.f(a)
        inv = r.g(a)
        cands = [(str(inv), 'swap') if inv is not None and inv >= 0 else None, (str(apply_rule(('+', k), a) if op == '×' else a * k), 'guess' if op != '×' else 'diff'),
                 (str(OPN['−' if op == '+' else '+'](a, k)) if OPN['−' if op == '+' else '+'](a, k) >= 0 else None, 'sign'), (str(ans + 10), 'calc'), (str(ans + k), 'step'), (str(ans - k) if ans >= k else None, 'step')]
        return Q(b, qid, diff, f'대응 관계를 나타낸 식이 △ = □ {op} {k} 입니다. □가 {a}일 때 △는 얼마일까요?', str(ans), cands,
                 '식의 □ 자리에 수를 넣어 계산해요.', f'△ = {a} {op} {k}', f'△ = {a} {op} {k} = {ans} 이에요.', f'첫 단계: □ 자리에 {eul(str(a))} 넣어요')
    def back_q(qid, diff, op, k, bval):
        r = Rel(op, k, 'tc', [1, 2, 3, 4]); ans = r.g(bval)
        assert ans is not None and ans >= 0
        fw = r.f(bval)
        return Q(b, qid, diff, f'대응 관계를 나타낸 식이 △ = □ {op} {k} 입니다. △가 {bval}일 때 □는 얼마일까요?', str(ans),
                 [(str(fw), 'inv'), (str(ans + k), 'calc'), (str(bval), 'guess'), (str(abs(ans - 1)), 'calc')],
                 '△를 알고 □를 구할 때는 거꾸로 계산해요.', f'{bval} = □ {op} {k} 에서 □를 구해요.', f'{bval} = □ {op} {k} 이므로 □ = {ans} 이에요.', f'첫 단계: 식의 △ 자리에 {eul(str(bval))} 넣어요. {bval} = □ {op} {k}')


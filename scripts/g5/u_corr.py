OPN = {'×': lambda a, k: a * k, '+': lambda a, k: a + k, '−': lambda a, k: a - k}
INV = {'×': lambda b, k: b // k if b % k == 0 else None, '+': lambda b, k: b - k, '−': lambda b, k: b + k}

class Rel:
    def __init__(self, op, k, set_, top, unit_a='', unit_b=''):
        self.op, self.k, self.set, self.top = op, k, set_, top
    def f(self, a): return OPN[self.op](a, self.k)
    def g(self, b): return INV[self.op](b, self.k)
    def formula(self): return f'△ = □ {self.op} {self.k}'
    def say(self):
        if self.op == '×': return f'△는 □의 {self.k}배예요'
        if self.op == '+': return f'△는 □보다 {self.k} 커요'
        return f'△는 □보다 {self.k} 작아요'
    def bot(self): return [self.f(a) for a in self.top]
    def spec(self, q=None):
        bot = [str(x) for x in self.bot()]
        if q is not None: bot[q] = 'q'
        return f'[[fig:tbl:{self.set}:{len(self.top)}:' + ':'.join(map(str, self.top)) + ':' + ':'.join(bot) + ']]'
    # 실수한 규칙들 (값, 유형)
    def wrong_rules(self):
        a0, b0 = self.top[0], self.f(self.top[0])
        step = self.f(self.top[1]) - self.f(self.top[0])
        out = []
        if self.op == '×':
            out.append((('+', b0 - a0), 'first'))
            out.append((('+', step), 'diff'))
        else:
            if a0 and b0 % a0 == 0 and b0 // a0 > 1:
                out.append((('×', b0 // a0), 'first'))
            out.append((('−' if self.op == '+' else '+', self.k), 'sign'))
        return out

def apply_rule(rule, a):
    op, k = rule
    v = OPN[op](a, k)
    return v if v >= 0 else None


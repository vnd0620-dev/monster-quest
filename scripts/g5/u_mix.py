    def ex(qid, diff, expr, word=None, unit='', extra=(), hint1=''):
        trace = []
        ans = calc(expr, 'ok', trace)
        assert ans.denominator == 1 and ans >= 0, (qid, expr, ans)
        a = int(ans)
        A = f'{a}{unit}'
        cands = []
        for mode, tag in (('rtl', 'rtl'), ('paren', 'paren'), ('order', 'order')):
            v = safe(expr, mode)
            if v is not None and v != ans and v <= 20 * ans + 100:
                cands.append((f'{int(v)}{unit}', tag))
        if len(trace) > 1 and trace[0][1].denominator == 1:
            cands.append((f'{int(trace[0][1])}{unit}', 'part'))
        for v, tag in extra:
            cands.append((f'{v}{unit}', tag))
        v = safe(expr, 'addfirst')
        if v is not None and v != ans and v <= 5 * ans + 50:
            cands.append((f'{int(v)}{unit}', 'order'))
        cands += [(f'{a + 10}{unit}', 'calc'), (f'{a - 10}{unit}' if a >= 10 else None, 'calc'), (f'{a + 1}{unit}', 'calc')]
        cands = [c for c in cands if c[0] is not None]
        steps = [f'{t}' for t, _ in trace]
        circ = '①②③④'
        hint2 = '계산 순서: ' + ' → '.join(f'{circ[i]} {s}' for i, s in enumerate(steps))
        explain = ' '.join(f'{circ[i]} {s} = {int(v) if v.denominator == 1 else v}' for i, (s, v) in enumerate(trace)) + f' → 답은 {ieyo(A)}.'
        text = word if word else f'{expr} = ?'
        step = f'첫 단계: 가장 먼저 계산할 곳은 {ieyo(steps[0])}' if len(steps) > 1 else f'첫 단계: {eul(steps[0])} 계산해요'
        if word:
            step = f'첫 단계: 하나의 식으로 쓰면 {expr} → 가장 먼저 {eul(steps[0])} 계산해요'
        return Q(b, qid, diff, text, A, cands, hint1, hint2, explain, step, {'expr': expr})

